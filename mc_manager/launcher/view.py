"""Minecraft-inspired desktop presentation, separate from launcher operations."""
import tkinter as tk
from tkinter import ttk

from .artwork import ArtCanvas, Artwork


def build_window(app):
    root = app.root
    root.title("Monkeycraft Launcher")
    root.geometry(f"1280x900+{max(0, (root.winfo_screenwidth() - 1280) // 2)}+{max(0, (root.winfo_screenheight() - 940) // 2)}")
    root.minsize(1120, 780)
    root.configure(background="#10150f")
    style = ttk.Style(root)
    style.theme_use("clam")
    style.configure(".", background="#1b2118", foreground="#edf1e3", font=("Segoe UI", 10))
    style.configure("TFrame", background="#10150f")
    style.configure("TLabel", background="#10150f")
    style.configure("Panel.TFrame", background="#1b2118")
    style.configure("Panel.TLabel", background="#1b2118")
    style.configure("Account.TFrame", background="#182014", relief="solid", borderwidth=1)
    style.configure("Account.TLabel", background="#182014", foreground="#c9d4b9")
    style.configure("Title.TLabel", font=("Consolas", 18, "bold"), foreground="#e6efcd")
    style.configure("Muted.TLabel", foreground="#a7b597")
    style.configure("TButton", padding=(12, 8), background="#3a4133", borderwidth=2,
                    bordercolor="#10150e", lightcolor="#727e5d", darkcolor="#252d1e", relief="raised")
    style.map("TButton", background=[("disabled", "#252d21"), ("pressed", "#28391c"), ("active", "#526343")],
              foreground=[("disabled", "#74806c")], lightcolor=[("active", "#a3bb82")])
    style.configure("Primary.TButton", background="#588b2e", foreground="#f8ffe9",
                    font=("Consolas", 14, "bold"), padding=(26, 10), lightcolor="#b8dd7c", darkcolor="#294915")
    style.map("Primary.TButton", background=[("disabled", "#303f24"), ("pressed", "#416f23"), ("active", "#75a840")],
              foreground=[("disabled", "#89967a")])
    style.configure("TEntry", fieldbackground="#182015", foreground="#edf1e3", insertcolor="#edf1e3", bordercolor="#687354")
    style.configure("TSpinbox", fieldbackground="#182015", foreground="#edf1e3")
    style.configure("TCheckbutton", background="#10150f", foreground="#b7c3a8")
    style.configure("Treeview", background="#1b2118", fieldbackground="#1b2118", rowheight=72,
                    borderwidth=0, bordercolor="#46553a", lightcolor="#46553a", darkcolor="#46553a", font=("Segoe UI", 10))
    style.configure("Treeview.Heading", background="#2a3523", foreground="#becba9",
                    bordercolor="#46553a", lightcolor="#46553a", darkcolor="#46553a", font=("Consolas", 10, "bold"), padding=(8, 8))
    style.map("Treeview", background=[("selected", "#3d512c")], foreground=[("selected", "#f3f7e9")])
    style.configure("TNotebook", background="#10150f", borderwidth=0, bordercolor="#46553a", lightcolor="#46553a", darkcolor="#46553a", tabmargins=(0, 0, 0, 10))
    style.configure("TNotebook.Tab", padding=(26, 10), background="#252e20", foreground="#a9b59a", bordercolor="#46553a", lightcolor="#46553a", darkcolor="#46553a", font=("Consolas", 11, "bold"))
    style.map("TNotebook.Tab", padding=[("selected", (26, 10))], background=[("selected", "#435b2e"), ("active", "#35452a")], foreground=[("selected", "#f6ffe6")])
    style.configure("Horizontal.TProgressbar", background="#82b64a", troughcolor="#202a1a", borderwidth=0)
    style.configure("Vertical.TScrollbar", background="#405033", troughcolor="#1b2118", bordercolor="#1b2118", arrowcolor="#b9c8a3")

    shell = ttk.Frame(root, padding=16)
    shell.pack(fill="both", expand=True)
    shell.columnconfigure(0, weight=1)
    shell.rowconfigure(1, weight=1)
    app.artwork = Artwork(root)
    app.header_art = ArtCanvas(shell, app.artwork, banner=True, height=168)
    app.header_art.grid(row=0, column=0, sticky="ew", pady=(0, 14))
    account = ttk.Frame(app.header_art, style="Account.TFrame", padding=12)
    account_window = app.header_art.create_window(0, 24, window=account, anchor="ne")
    app.header_art.bind("<Configure>", lambda event: app.header_art.coords(account_window, event.width - 24, 24), add="+")
    ttk.Label(account, text="YOUR MICROSOFT ACCOUNT", style="Account.TLabel", font=("Consolas", 10, "bold")).pack(anchor="w", pady=(0, 8))
    account_buttons = ttk.Frame(account, style="Account.TFrame")
    account_buttons.pack(anchor="w")
    app._button(account_buttons, "Sign in with Microsoft", app.sign_in).pack(side="left", padx=(0, 6))
    app.retry_account_button = app._button(account_buttons, "Retry saved account", app.retry_account)
    app.retry_account_button.pack(side="left", padx=(0, 6))
    app._button(account_buttons, "Sign out", app.sign_out).pack(side="left")
    ttk.Label(account, textvariable=app.account, style="Account.TLabel", wraplength=440).pack(anchor="w", pady=(8, 0))

    app.tabs = ttk.Notebook(shell)
    app.tabs.grid(row=1, column=0, sticky="nsew")
    play = ttk.Frame(app.tabs, padding=(0, 4, 0, 0))
    setup = ttk.Frame(app.tabs, padding=24)
    activity = ttk.Frame(app.tabs, padding=16)
    app.tabs.add(play, text="PLAY & MODPACKS")
    app.tabs.add(setup, text="LAUNCHER SETUP")
    app.tabs.add(activity, text="ACTIVITY")
    play.columnconfigure(0, minsize=368)
    play.columnconfigure(1, weight=1)
    play.rowconfigure(0, weight=1)

    sidebar = ttk.Frame(play, style="Panel.TFrame")
    sidebar.grid(row=0, column=0, sticky="nsew", padx=(0, 18))
    sidebar.columnconfigure(0, weight=1)
    sidebar.rowconfigure(1, weight=1)
    library_title = ArtCanvas(sidebar, app.artwork, height=58)
    library_title.asset, library_title.badge = "stone.png", "YOUR WORLDS"
    library_title.grid(row=0, column=0, columnspan=2, sticky="ew")
    app.profiles = ttk.Treeview(sidebar, columns=("version", "status"), displaycolumns=("status",),
                                selectmode="browse", height=5)
    app.profiles.heading("#0", text="PROFILE")
    app.profiles.heading("status", text="ON THIS PC")
    app.profiles.column("#0", width=238, minwidth=160)
    app.profiles.column("version", width=0, stretch=False)
    app.profiles.column("status", width=112, minwidth=105, stretch=False)
    app.profiles.grid(row=1, column=0, sticky="nsew")
    profile_scroll = ttk.Scrollbar(sidebar, command=app.profiles.yview)
    profile_scroll.grid(row=1, column=1, sticky="ns")
    app.profiles.configure(yscrollcommand=profile_scroll.set)
    app.profiles.bind("<<TreeviewSelect>>", app._selection)
    app.profiles.bind("<Button-1>", lambda event: "break" if app.busy else None)
    app.profiles.bind("<Key>", lambda event: "break" if app.busy else None)
    for state, color in {"installed": "#b7dc89", "release_changed": "#e6c77e", "blocked": "#e7a09a", "repair": "#e6c77e", "recover": "#e6c77e"}.items():
        app.profiles.tag_configure(state, foreground=color)
    sidebar_footer = ttk.Frame(sidebar, style="Panel.TFrame", padding=12)
    sidebar_footer.grid(row=2, column=0, columnspan=2, sticky="ew")
    ttk.Label(sidebar_footer, textvariable=app.library_summary, style="Panel.TLabel", wraplength=320).pack(anchor="w", pady=(0, 10))
    app._button(sidebar_footer, "Refresh status", app.rescan).pack(anchor="w")

    stage = ttk.Frame(play, style="Panel.TFrame")
    stage.grid(row=0, column=1, sticky="nsew")
    stage.columnconfigure(0, weight=1)
    stage.rowconfigure(1, weight=1)
    app.pack_art = ArtCanvas(stage, app.artwork, height=220)
    app.pack_art.grid(row=0, column=0, sticky="ew")
    # Give the profile details room on shorter displays while retaining its art.
    root.bind("<Configure>", lambda event: app.pack_art.configure(height=max(130, min(220, event.height - 680)))
              if event.widget == root else None, add="+")
    details = ttk.Frame(stage, style="Panel.TFrame", padding=(18, 14, 18, 8))
    details.grid(row=1, column=0, sticky="nsew")
    details.columnconfigure(0, weight=1)
    details.rowconfigure(0, weight=1)
    app.detail_text = tk.Text(details, height=5, width=38, background="#1b2118", foreground="#e7ecd9",
                              relief="flat", wrap="word", font=("Segoe UI", 10), state="disabled", highlightthickness=0)
    app.detail_text.tag_configure("title", font=("Consolas", 18, "bold"), foreground="#f0f3e0")
    app.detail_text.grid(row=0, column=0, sticky="nsew")
    detail_scroll = ttk.Scrollbar(details, command=app.detail_text.yview)
    detail_scroll.grid(row=0, column=1, sticky="ns")
    app.detail_text.configure(yscrollcommand=detail_scroll.set)
    app.details.trace_add("write", app._render_details)
    app._render_details()
    ttk.Label(details, textvariable=app.instance, style="Panel.TLabel", foreground="#9daa8d").grid(row=1, column=0, columnspan=2, sticky="w", pady=(10, 4))
    links = ttk.Frame(stage, style="Panel.TFrame", padding=(18, 0, 18, 8))
    links.grid(row=2, column=0, sticky="ew")
    app.folder_button = app._button(links, "Open folder", app.open_instance)
    app.folder_button.pack(side="left", padx=(0, 6))
    app.log_button = app._button(links, "Game log", app.show_game_log)
    app.log_button.pack(side="left", padx=(0, 6))
    app.server_button = app._button(links, "Copy server", app.copy_server)
    app.server_button.pack(side="left")
    actions = ttk.Frame(stage, style="Panel.TFrame", padding=(18, 0, 18, 14))
    actions.grid(row=3, column=0, sticky="ew")
    app.play_button = app._button(actions, "PLAY", app.play, primary=True)
    app.play_button.pack(side="left", padx=(0, 10))
    app.install_button = app._button(actions, "Install / repair", app.install)
    app.install_button.pack(side="left", padx=(0, 6))
    app._button(actions, "Check files", app.check).pack(side="left", padx=(0, 6))
    app.recover_button = app._button(actions, "Recover", app.recover)
    app.recover_button.pack(side="left", padx=(0, 6))
    app.cancel_button = ttk.Button(actions, text="Cancel", command=app.cancel_operation, state="disabled")
    app.cancel_button.pack(side="right")

    setup.columnconfigure(1, weight=1)
    ttk.Label(setup, text="CONNECT YOUR WORLDS", style="Title.TLabel").grid(row=0, column=0, columnspan=4, sticky="w", pady=(0, 12))
    ttk.Label(setup, text="Load a catalog from your server panel, choose where your clients live, and tune Java and memory.",
              style="Muted.TLabel").grid(row=1, column=0, columnspan=4, sticky="w", pady=(0, 24))
    ttk.Label(setup, text="Pack catalog").grid(row=2, column=0, sticky="w", padx=(0, 12))
    source = ttk.Entry(setup, textvariable=app.source)
    source.grid(row=2, column=1, sticky="ew", padx=(0, 8))
    app.controls.append(source)
    app._button(setup, "Browse…", app.browse_catalog).grid(row=2, column=2, padx=(0, 8))
    app._button(setup, "Load catalog", app.refresh).grid(row=2, column=3)
    network = ttk.Checkbutton(setup, text="Allow HTTP on a trusted local network", variable=app.allow_http)
    network.grid(row=3, column=1, columnspan=3, sticky="w", pady=(10, 26))
    app.controls.append(network)
    ttk.Label(setup, text="Instance library").grid(row=4, column=0, sticky="w", padx=(0, 12))
    library = ttk.Entry(setup, textvariable=app.library)
    library.grid(row=4, column=1, columnspan=2, sticky="ew", padx=(0, 8))
    app.controls.append(library)
    app._button(setup, "Choose folder…", app.browse_library).grid(row=4, column=3)
    ttk.Label(setup, text="Memory (MiB)").grid(row=5, column=0, sticky="w", pady=24)
    memory = ttk.Spinbox(setup, from_=512, to=65536, increment=512, textvariable=app.memory, width=10)
    memory.grid(row=5, column=1, sticky="w")
    app.controls.append(memory)
    app._button(setup, "Account / Java settings…", app.account_settings).grid(row=5, column=2, columnspan=2, sticky="e")
    app._button(setup, "Save settings", app.save_and_scan).grid(row=6, column=3, sticky="e")
    ttk.Label(setup, text="Your instances, worlds, and account stay on this PC.", style="Muted.TLabel").grid(row=7, column=0, columnspan=4, sticky="w", pady=28)

    activity.columnconfigure(0, weight=1)
    activity.rowconfigure(1, weight=1)
    ttk.Label(activity, text="LAUNCHER ACTIVITY", style="Title.TLabel").grid(row=0, column=0, sticky="w", pady=(0, 14))
    app.log = tk.Text(activity, height=10, background="#161d12", foreground="#c1d1ac", relief="flat",
                      font=("Consolas", 10), wrap="word", state="disabled", highlightthickness=0, padx=12, pady=12)
    app.log.grid(row=1, column=0, sticky="nsew")
    log_scroll = ttk.Scrollbar(activity, command=app.log.yview)
    log_scroll.grid(row=1, column=1, sticky="ns")
    app.log.configure(yscrollcommand=log_scroll.set)
    app.progress = ttk.Progressbar(shell, mode="determinate", maximum=100)
    app.progress.grid(row=2, column=0, sticky="ew", pady=(14, 8))
    ttk.Label(shell, textvariable=app.status, wraplength=1050, style="Muted.TLabel").grid(row=3, column=0, sticky="w")
    if not app.source.get():
        app.tabs.select(setup)
